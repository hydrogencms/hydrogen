func TestDeterministic(t *testing.T) {
	types, groups := fixture()
	wantGo, err := Go(types, groups, GoOptions{Package: "gen"})
	if err != nil {
		t.Fatal(err)
	}
	wantTS, err := TypeScript(types, groups, TSOptions{})
	if err != nil {
		t.Fatal(err)
	}
	rng := rand.New(rand.NewPCG(1, 2))
	for range 10 {
		ts := slices.Clone(types)
		rng.Shuffle(len(ts), func(i, j int) { ts[i], ts[j] = ts[j], ts[i] })
		gotGo, err := Go(ts, groups, GoOptions{Package: "gen"})
		if err != nil {
			t.Fatal(err)
		}
		for n, src := range wantGo {
			if !bytes.Equal(src, gotGo[n]) {
				t.Fatalf("%s differs after shuffling input", n)
			}
		}
		gotTS, err := TypeScript(ts, groups, TSOptions{})
		if err != nil || !bytes.Equal(gotTS, wantTS) {
			t.Fatalf("TypeScript differs after shuffling input (err %v)", err)
		}
	}
}

