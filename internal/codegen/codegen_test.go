func TestEnumConstantCollisionsGetSuffixes(t *testing.T) {
	f := &schema.Field{Name: "locale", Type: "enum", Shape: schema.Shape{Base: schema.BaseString, Format: "enum",
		Enum: []string{"en_US", "en-US", "en-US2", "en US"}}}
	files, err := Go([]*schema.Type{{Name: "x", Fields: []*schema.Field{f}}}, nil, GoOptions{})
	if err != nil {
		t.Fatal(err)
	}
	src := strings.Join(strings.Fields(string(files["x.go"])), " ")
	// value order: "en US" < "en-US" < "en-US2" < "en_US"; "en US" keeps the plain name.
	for _, want := range []string{`XLocaleEnUs XLocale = "en US"`, `XLocaleEnUs2 XLocale = "en-US2"`,
		`XLocaleEnUs3 XLocale = "en-US"`, `XLocaleEnUs4 XLocale = "en_US"`} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in:\n%s", want, src)
		}
	}
	again, _ := Go([]*schema.Type{{Name: "x", Fields: []*schema.Field{f}}}, nil, GoOptions{})
	if !bytes.Equal(again["x.go"], files["x.go"]) {
		t.Error("output is not deterministic")
	}
}

func TestTypeScriptLiterals(t *testing.T) {
	f := &schema.Field{Name: "k", Type: "enum", Description: "ends */ early", Shape: schema.Shape{Base: schema.BaseString,
		Format: "enum", Enum: []string{"caf\u00e9", "\U0001F600", "a\"b", "x\u2028y", "<b>"}}}
	out, err := TypeScript([]*schema.Type{{Name: "x", Description: "a */ b", Fields: []*schema.Field{f}}}, nil, TSOptions{})
	if err != nil {
		t.Fatal(err)
	}
	src := string(out)
	for _, want := range []string{`"café"`, `"😀"`, `"a\"b"`, `"x\u2028y"`, `"\u003cb\u003e"`, `ends *\/ early`, `a *\/ b`} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in:\n%s", want, src)
		}
	}
	if strings.Contains(src, `\U`) {
		t.Errorf("Go-style \\U escape in:\n%s", src)
	}
}
