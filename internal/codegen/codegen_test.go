func TestErrors(t *testing.T) {
	text := func(name string) *schema.Field { return str(name, "", false) }
	grp := func(name string, fields ...*schema.Field) *schema.Field {
		return &schema.Field{Name: name, Type: "group", Shape: schema.Shape{Base: schema.BaseGroup}, Fields: fields}
	}
	enum := func(name string, vals ...string) *schema.Field {
		return &schema.Field{Name: name, Type: "enum", Shape: schema.Shape{Base: schema.BaseString, Format: "enum", Enum: vals}}
	}
	tp := func(name string, fields ...*schema.Field) *schema.Type {
		return &schema.Type{Name: name, Fields: fields}
	}

	tests := []struct {
		name   string
		types  []*schema.Type
		groups []*schema.Group
		want   string
	}{
		{"inline group vs type", []*schema.Type{tp("article", grp("address", text("a"))), tp("articleAddress")}, nil, "ArticleAddress"},
		{"handle vs type", []*schema.Type{tp("article"), tp("articleType")}, nil, "ArticleType"},
		{"types helper", []*schema.Type{tp("types")}, nil, "Types"},
		{"group vs type", []*schema.Type{tp("seoGroup")}, []*schema.Group{{Name: "seo"}}, "SeoGroup"},
		{"field names", []*schema.Type{tp("a", text("fooBar"), text("foo_bar"))}, nil, "FooBar"},
		{"enum value vs type", []*schema.Type{tp("a", enum("k", "x"), enum("kX", "y"))}, nil, "AKX"},
		{"duplicate type", []*schema.Type{tp("a"), tp("a")}, nil, "twice"},
		{"duplicate field", []*schema.Type{tp("a", text("x"), text("x"))}, nil, "both become"},
		{"bad type name", []*schema.Type{tp("a b")}, nil, "invalid type name"},
		{"bad field name", []*schema.Type{tp("a", text("x\"y"))}, nil, "invalid field name"},
		{"unknown group", []*schema.Type{tp("a", &schema.Field{Name: "g", Group: "nope", Shape: schema.Shape{Base: schema.BaseGroup}})}, nil, "unknown group"},
		{"list without element", []*schema.Type{tp("a", &schema.Field{Name: "l", Shape: schema.Shape{Base: schema.BaseList}})}, nil, "element"},
		{"unknown base", []*schema.Type{tp("a", &schema.Field{Name: "l", Shape: schema.Shape{Base: "weird"}})}, nil, "unsupported"},
		{"file name", []*schema.Type{tp("blog_post"), tp("blogPost")}, nil, "BlogPost"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Go(tc.types, tc.groups, GoOptions{})
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("Go error = %v, want containing %q", err, tc.want)
			}
		})
	}
}

func TestKeywordNamesCompileAsIdentifiers(t *testing.T) {
	types := []*schema.Type{
		{Name: "type", Fields: []*schema.Field{str("func", "", true), str("package", "", false), str("1st", "", false), str("go-to", "", false)}},
		{Name: "struct"},
	}
	files, err := Go(types, nil, GoOptions{})
	if err != nil {
		t.Fatal(err)
	}
	src := string(files["type.go"])
	for _, want := range []string{"type Type struct", "Func ", "Package ", "X1st ", "GoTo ", "var TypeType"} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in:\n%s", want, src)
		}
	}
	if _, ok := files["struct.go"]; !ok {
		t.Error("struct.go missing")
	}
}

