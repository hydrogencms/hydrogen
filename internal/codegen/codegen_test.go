var update = flag.Bool("update", false, "rewrite the golden files")

func golden(t *testing.T, name string, got []byte) {
	t.Helper()
	path := filepath.Join("testdata", name)
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (run with -update)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("%s differs from the generated output (run with -update and review the diff)\n--- got ---\n%s", name, got)
	}
}

func TestGoGolden(t *testing.T) {
	types, groups := fixture()
	files, err := Go(types, groups, GoOptions{})
	if err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(files))
	for n, src := range files {
		names = append(names, n)
		if !bytes.HasPrefix(src, []byte("// Code generated by hydrogen. DO NOT EDIT.\n")) {
			t.Errorf("%s lacks the header", n)
		}
	}
	slices.Sort(names)
	if want := []string{"article.go", "blog_post.go", "doc.go", "groups.go", "image.go", "person.go"}; !slices.Equal(names, want) {
		t.Fatalf("files = %v, want %v", names, want)
	}
	for _, n := range names {
		golden(t, n+".golden", files[n])
	}
}

