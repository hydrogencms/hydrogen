package projectfile

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"go/types"
	"regexp"
	"strconv"
	"strings"
	"unicode"

	"github.com/hydrogencms/hydrogen/internal/modcat"
)

var versionEl = regexp.MustCompile(`^v[0-9]+$`)

// alias derives an import name from a package path's last element (skipping a /vN suffix and a
// "hydrogen-" prefix): hydrogen-stripe → stripe.
func alias(path string) string {
	els := strings.Split(path, "/")
	last := els[len(els)-1]
	if versionEl.MatchString(last) && len(els) > 1 {
		last = els[len(els)-2]
	}
	if rest := strings.TrimPrefix(strings.TrimPrefix(last, "hydrogen-"), "hydrogen_"); rest != "" {
		last = rest
	}
	var b strings.Builder
	for _, r := range strings.ToLower(last) {
		if unicode.IsLetter(r) && r < unicode.MaxASCII || unicode.IsDigit(r) {
			b.WriteRune(r)
		}
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "m" + s
	}
	return s
}

// reserved names an import must not take: keywords, predeclared identifiers and the names the generated
// file and the project's main package use.
func reserved(name string) bool {
	switch name {
	case "main", "init", "configure", "useModules", "hydrogen", "h", "_":
		return true
	}
	return token.IsKeyword(name) || types.Universe.Lookup(name) != nil
}

// aliases gives every entry a distinct import name. Catalog modules claim theirs first, so a third-party
// module never renames a first-party one whatever the order of the list.
func aliases(modules []string) []string {
	out := make([]string, len(modules))
	taken := map[string]bool{}
	claim := func(i int) {
		base := alias(ImportPath(modules[i]))
		if reserved(base) {
			base += "mod"
		}
		name := base
		for n := 2; taken[name] || reserved(name); n++ {
			name = base + strconv.Itoa(n)
		}
		taken[name] = true
		out[i] = name
	}
	for i, m := range modules {
		if _, ok := modcat.Lookup(m); ok {
			claim(i)
		}
	}
	for i, m := range modules {
		if _, ok := modcat.Lookup(m); !ok {
			claim(i)
		}
	}
	return out
}

// Generate returns the source of modules_gen.go for a validated module list.
func Generate(modules []string) ([]byte, error) {
	names := aliases(modules)
	var b bytes.Buffer
	b.WriteString("// Code generated by hydrogen from hydrogen.yaml; DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\t\"github.com/hydrogencms/hydrogen\"\n")
	for i, m := range modules {
		path := ImportPath(m)
		last := path[strings.LastIndex(path, "/")+1:]
		if _, ok := modcat.Lookup(m); ok && names[i] == last {
			fmt.Fprintf(&b, "\t%q\n", path)
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", names[i], path)
		}
	}
	b.WriteString(")\n\n// useModules registers the modules listed in hydrogen.yaml.\nfunc useModules(h *hydrogen.Builder) {\n")
	if len(modules) > 0 {
		b.WriteString("\th.Use(\n")
		for i := range modules {
			fmt.Fprintf(&b, "\t\t%s.Module(),\n", names[i])
		}
		b.WriteString("\t)\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generating %s: %w", GenName, err)
	}
	return out, nil
}
