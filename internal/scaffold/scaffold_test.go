func TestWrite(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "acme")
	if err := Write(Options{Dir: dir, Module: "example.com/acme", Core: "../.."}); err != nil {
		t.Fatal(err)
	}
	for _, f := range []string{"go.mod", "main.go", "hydrogen.go", "hydrogen.yaml", "modules_gen.go", "config/app.yaml", "schema/article.yaml", ".gitignore", "README.md",
		"admin/package.json", "admin/svelte.config.js", "admin/vite.config.ts", "admin/tsconfig.json", "admin/src/elements.ts", "admin/src/Hello.svelte",
		"admin/logo.svg", "admin/theme.css", "admin/strings.json"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err != nil {
			t.Errorf("missing %s", f)
		}
	}
	gomod, _ := os.ReadFile(filepath.Join(dir, "go.mod"))
	if !strings.Contains(string(gomod), "module example.com/acme") || !strings.Contains(string(gomod), "github.com/hydrogencms/hydrogen => ") {
		t.Fatalf("go.mod:\n%s", gomod)
	}
	yml, _ := os.ReadFile(filepath.Join(dir, "hydrogen.yaml"))
	if !strings.Contains(string(yml), "  - sqlite\n  - postgres\n") {
		t.Fatalf("hydrogen.yaml:\n%s", yml)
	}
	gen, _ := os.ReadFile(filepath.Join(dir, "modules_gen.go"))
	if !strings.Contains(string(gen), "Code generated by hydrogen from hydrogen.yaml; DO NOT EDIT.") || !strings.Contains(string(gen), "sqlite.Module()") {
		t.Fatalf("modules_gen.go:\n%s", gen)
	}
	hy, _ := os.ReadFile(filepath.Join(dir, "hydrogen.go"))
	if !strings.Contains(string(hy), "useModules(h)") {
		t.Fatalf("hydrogen.go:\n%s", hy)
	}
	if err := Write(Options{Dir: dir}); err == nil {
		t.Fatal("writing into a non-empty directory succeeded")
	}
}

func TestWriteRejectsBadCore(t *testing.T) {
	if err := Write(Options{Dir: filepath.Join(t.TempDir(), "x"), Core: t.TempDir()}); err == nil {
		t.Fatal("accepted a core directory without hydrogen.go")
	}
}

func TestWriteAdminStarter(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "acme")
	if err := Write(Options{Dir: dir}); err != nil {
		t.Fatal(err)
	}
	yaml, _ := os.ReadFile(filepath.Join(dir, "config/app.yaml"))
	for _, want := range []string{"#   elements: [./admin/dist/elements.js]", "#   widgets: { hello: x-hello }"} {
		if !strings.Contains(string(yaml), want) {
			t.Errorf("app.yaml lacks %q", want)
		}
	}
	vite, _ := os.ReadFile(filepath.Join(dir, "admin/vite.config.ts"))
	if !strings.Contains(string(vite), "ADMIN_PREFIX") || !strings.Contains(string(vite), "elements.js") {
		t.Errorf("vite.config.ts:\n%s", vite)
	}
	svelte, _ := os.ReadFile(filepath.Join(dir, "admin/svelte.config.js"))
	if !strings.Contains(string(svelte), "customElement: true") {
		t.Errorf("svelte.config.js:\n%s", svelte)
	}
	pkg, _ := os.ReadFile(filepath.Join(dir, "admin/package.json"))
	if !strings.Contains(string(pkg), `"@hydrogencms/admin-sdk": "`+npmRange+`"`) {
		t.Errorf("package.json:\n%s", pkg)
	}
	readme, _ := os.ReadFile(filepath.Join(dir, "README.md"))
	if strings.Contains(string(readme), "not published yet") || !strings.Contains(string(readme), "ADMIN_PREFIX") ||
		!strings.Contains(string(readme), "first administrator") {
		t.Errorf("README:\n%s", readme)
	}

	local := filepath.Join(t.TempDir(), "acme")
	if err := Write(Options{Dir: local, Core: "../.."}); err != nil {
		t.Fatal(err)
	}
	pkg, _ = os.ReadFile(filepath.Join(local, "admin/package.json"))
	if !strings.Contains(string(pkg), `"@hydrogencms/admin-sdk": "file:`) || !strings.Contains(string(pkg), "packages/admin-sdk") {
		t.Errorf("package.json with -core:\n%s", pkg)
	}
	readme, _ = os.ReadFile(filepath.Join(local, "README.md"))
	if !strings.Contains(string(readme), "installed from your hydrogen checkout") {
		t.Errorf("README with -core:\n%s", readme)
	}
}

func TestWriteStatic(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "docs")
	if err := Write(Options{Dir: dir, Module: "example.com/docs", Core: "../..", Static: true}); err != nil {
		t.Fatal(err)
	}
	for _, f := range []string{"go.mod", "main.go", "hydrogen.go", "hydrogen.yaml", "modules_gen.go", "config/app.yaml", "config/channels.yaml",
		"schema/types.yaml", "schema/blocks.yaml", ".gitignore", "README.md", ".github/workflows/deploy.yml",
		"content/manifest.json", "content/items.ndjson", "content/schema/compiled.json", "content/modules/pages.ndjson",
		"site/package.json", "site/astro.config.mjs", "site/tsconfig.json", "site/public/favicon.svg", "site/src/env.d.ts", "site/src/hydrogen.ts",
		"site/src/pages/[...path].astro", "site/src/pages/404.astro", "site/src/layouts/Layout.astro", "site/src/templates/Page.astro",
		"site/src/components/registry.ts", "site/src/components/blocks/Hero.astro", "site/src/components/blocks/Text.astro",
		"site/src/components/blocks/Features.astro", "site/src/components/blocks/Feature.astro", "site/src/components/blocks/Callout.astro",
		"site/src/lib/link.ts", "site/src/styles/site.css"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err != nil {
			t.Errorf("missing %s", f)
		}
	}
	for _, f := range []string{"schema/article.yaml", "admin", "config/app.yaml.tmpl", "gitignore.tmpl"} {
		if _, err := os.Stat(filepath.Join(dir, f)); err == nil {
			t.Errorf("unexpected %s", f)
		}
	}
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	has := func(name string, want ...string) {
		t.Helper()
		got := read(name)
		for _, w := range want {
			if !strings.Contains(got, w) {
				t.Errorf("%s lacks %q:\n%s", name, w, got)
			}
		}
	}
	has("hydrogen.yaml", "  - sqlite\n  - pages\n")
	has("modules_gen.go", "pages.Module()", "sqlite.Module()")
	if strings.Contains(read("go.mod"), "postgres") {
		t.Errorf("go.mod requires postgres:\n%s", read("go.mod"))
	}
	has("go.mod", "module example.com/docs", "github.com/hydrogencms/hydrogen/modules/sqlite => ")
	has("config/app.yaml", "files: content", "sqlite:.work/hydrogen.db")
	has("config/channels.yaml", `frontend: "${env:SITE_URL:-http://localhost:4321}"`, "match: { prefix: / }", "site: main")
	has(".gitignore", "/.work/", "/site/node_modules/", "/site/dist/", "/site/.astro/")
	has("site/package.json", `"@hydrogencms/astro": "file:`, `"@hydrogencms/client": "file:`, `"@hydrogencms/bridge": "file:`, "packages/astro")
	has("site/astro.config.mjs", "output: 'static'", "process.env.SITE_URL", "process.env.SITE_BASE")
	has("site/src/pages/[...path].astro", "export function getStaticPaths()", "hydrogen.staticPaths()")
	has("README.md", "hydrogen content:save", "Source to **GitHub Actions**", "`file:` dependencies on your hydrogen checkout")
	has(".github/workflows/deploy.yml", "actions/checkout@v7", "actions/setup-go@v7", "actions/setup-node@v7", "actions/configure-pages@v6",
		"actions/upload-pages-artifact@v5", "actions/deploy-pages@v5", "APP_ENV: production", "steps.pages.outputs.origin", "steps.pages.outputs.base_path", "site/dist")

	published := filepath.Join(t.TempDir(), "docs")
	if err := Write(Options{Dir: published, Static: true}); err != nil {
		t.Fatal(err)
	}
	pkg, _ := os.ReadFile(filepath.Join(published, "site/package.json"))
	if !strings.Contains(string(pkg), `"@hydrogencms/astro": "`+npmRange+`"`) || strings.Contains(string(pkg), "bridge") || strings.Contains(string(pkg), "file:") {
		t.Errorf("site/package.json:\n%s", pkg)
	}
}
