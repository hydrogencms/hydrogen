package siteexport

import (
	"encoding/json"
	"fmt"
	"html"
	"net/url"
	"regexp"
	"slices"
	"strings"
)

// redirect is one retired URL of a channel and where it goes.
type redirect struct {
	Root   string // the host directory its files go to
	Host   string // the host its channel matches, "" for any
	From   string // path as requested, with the channel's prefix
	To     string // the Location, a path or an absolute URL
	Status int
}

type redirectFile struct {
	Name string // relative to the tree
	Data []byte
	Kind string
	Root string
}

// redirectFiles renders the redirects of every root directory in the configured formats. Roots without
// redirects still get their (empty) file so a deploy always finds it.
func redirectFiles(formats []string, roots []string, rs []redirect, taken map[string]bool) ([]redirectFile, []string) {
	byRoot := map[string][]redirect{}
	for _, r := range rs {
		byRoot[r.Root] = append(byRoot[r.Root], r)
	}
	var out []redirectFile
	var warns []string
	for _, root := range roots {
		list := byRoot[root]
		slices.SortFunc(list, func(a, b redirect) int { return strings.Compare(a.From, b.From) })
		for _, f := range formats {
			switch f {
			case "netlify":
				out = append(out, redirectFile{root + "/_redirects", netlify(list), kindRedirects, root})
			case "s3":
				data, w := s3Rules(list)
				warns = append(warns, w...)
				out = append(out, redirectFile{root + "/s3-routing-rules.json", data, kindRedirects, root})
			case "html":
				for _, r := range list {
					name, ok := refreshFile(root, r.From)
					if !ok {
						warns = append(warns, fmt.Sprintf("redirect %s: no safe file name for its refresh page", r.From))
						continue
					}
					if taken[name] || taken[strings.ToLower(name)] {
						continue
					}
					out = append(out, redirectFile{name, refreshPage(r.To), kindRedirect, root})
				}
			}
		}
	}
	if slices.Contains(formats, "nginx") {
		data, w := nginx(rs)
		warns = append(warns, w...)
		out = append(out, redirectFile{"redirects.nginx.conf", data, kindRedirects, ""})
	}
	return out, warns
}

func refreshFile(root, from string) (string, bool) {
	u, err := url.Parse(from)
	if err != nil || !strings.HasPrefix(u.Path, "/") {
		return "", false
	}
	p := strings.Trim(u.Path, "/")
	last := p[strings.LastIndex(p, "/")+1:]
	var rel string
	switch {
	case p == "":
		rel = root + "/index.html"
	case strings.Contains(last, "."):
		rel = root + "/" + p
	default:
		rel = root + "/" + p + "/index.html"
	}
	return rel, safeRel(rel)
}

func refreshPage(to string) []byte {
	e := html.EscapeString(to)
	return []byte(`<!doctype html>
<html><head><meta charset="utf-8"><title>Redirecting</title>
<link rel="canonical" href="` + e + `">
<meta name="robots" content="noindex">
<meta http-equiv="refresh" content="0; url=` + e + `">
</head><body><p>Moved to <a href="` + e + `">` + e + `</a>.</p></body></html>
`)
}

func netlify(rs []redirect) []byte {
	var b strings.Builder
	b.WriteString("# Generated by hydrogen site:export\n")
	for _, r := range rs {
		if strings.ContainsAny(r.From+r.To, " \t\r\n") {
			continue
		}
		fmt.Fprintf(&b, "%s %s %d\n", r.From, r.To, r.Status)
	}
	return []byte(b.String())
}

// nginx writes two maps for the whole tree, keyed by host and path ($host$uri), so one file serves every host:
//
//	http { include /srv/site/redirects.nginx.conf; ... }
//	server { if ($hydrogen_redirect_to) { return $hydrogen_redirect_status $hydrogen_redirect_to; } ... }
//
// A channel that matches any host is keyed by a regular expression that accepts every host.
func nginx(rs []redirect) ([]byte, []string) {
	var warns []string
	var to, st strings.Builder
	list := slices.Clone(rs)
	slices.SortFunc(list, func(a, b redirect) int { return strings.Compare(a.Host+" "+a.From, b.Host+" "+b.From) })
	for _, r := range list {
		if strings.ContainsAny(r.From+r.To+r.Host, "\"\\$;{}\r\n") {
			warns = append(warns, fmt.Sprintf("redirect %s: left out of the nginx map (it contains a character nginx would interpret)", r.From))
			continue
		}
		key := `"` + r.Host + r.From + `"`
		if r.Host == "" {
			key = `"~^[^/]+` + regexp.QuoteMeta(r.From) + `$"`
		}
		fmt.Fprintf(&to, "    %s \"%s\";\n", key, r.To)
		fmt.Fprintf(&st, "    %s %d;\n", key, r.Status)
	}
	return []byte("# Generated by hydrogen site:export\nmap $host$uri $hydrogen_redirect_to {\n    default \"\";\n" + to.String() + "}\n" +
		"map $host$uri $hydrogen_redirect_status {\n    default 301;\n" + st.String() + "}\n"), warns
}

type s3Rule struct {
	Condition struct {
		KeyPrefixEquals string `json:"KeyPrefixEquals"`
		// Only a missing key redirects, so a live sibling (/news-archive next to /news) is never caught.
		HTTPErrorCodeReturnedEquals string `json:"HttpErrorCodeReturnedEquals"`
	} `json:"Condition"`
	Redirect struct {
		Protocol         string `json:"Protocol,omitempty"`
		HostName         string `json:"HostName,omitempty"`
		ReplaceKeyWith   string `json:"ReplaceKeyWith"`
		HTTPRedirectCode string `json:"HttpRedirectCode"`
	} `json:"Redirect"`
}

// maxS3Rules is the number of routing rules S3 accepts.
const maxS3Rules = 50

// s3Rules writes the RoutingRules of an S3 static website configuration. A rule matches by key prefix, so
// every old path also redirects the paths below it; longer prefixes are listed first.
func s3Rules(rs []redirect) ([]byte, []string) {
	var warns []string
	rules := []s3Rule{}
	list := slices.Clone(rs)
	slices.SortStableFunc(list, func(a, b redirect) int { return len(b.From) - len(a.From) })
	for _, r := range list {
		var rule s3Rule
		rule.Condition.HTTPErrorCodeReturnedEquals = "404"
		rule.Condition.KeyPrefixEquals = strings.TrimLeft(r.From, "/")
		if rule.Condition.KeyPrefixEquals == "" {
			warns = append(warns, "redirect /: S3 routing rules cannot redirect the site root")
			continue
		}
		rule.Redirect.HTTPRedirectCode = fmt.Sprint(r.Status)
		if u, err := url.Parse(r.To); err == nil && u.Host != "" {
			rule.Redirect.Protocol, rule.Redirect.HostName = u.Scheme, u.Host
			rule.Redirect.ReplaceKeyWith = strings.TrimLeft(u.RequestURI(), "/")
		} else {
			rule.Redirect.ReplaceKeyWith = strings.TrimLeft(r.To, "/")
		}
		if len(rules) == maxS3Rules {
			warns = append(warns, fmt.Sprintf("redirects: S3 accepts %d routing rules; %s and later ones were left out", maxS3Rules, r.From))
			break
		}
		rules = append(rules, rule)
	}
	b, _ := json.MarshalIndent(rules, "", "  ")
	return append(b, '\n'), warns
}
